package io.hammerhall.cli;

/**
 * Ожидаемая ошибка: нет токена, файл не найден, сервер отказал.
 *
 * <p>Отличается от прочих исключений тем, что её текст показывается
 * пользователю целиком и без стектрейса. Значит формулировка — часть
 * интерфейса: «Файл не найден: X» полезно, «NoSuchFileException» нет.
 *
 * <h3>🔑 Зачем здесь код ответа</h3>
 *
 * Один и тот же код у разных ручек означает разное, и перевести его
 * в слова может только тот, кто знает, куда ходил. {@code 401} на
 * {@code /profile} — «ключ не принят, перевыпустите». {@code 401} на
 * {@code /auth/token} — «не подошли почта или пароль»: ключа там ещё
 * нет и перевыпускать нечего. Совет «перевыпустите ключ» человеку,
 * который просто ошибся паролем, отправляет его чинить исправное.
 *
 * <p>Поэтому {@link ApiClient} по-прежнему переводит коды сам — это
 * верное умолчание для трёх команд из четырёх, — но оставляет число
 * в исключении. Вызывающий, у которого свой смысл, ловит и говорит
 * своими словами; остальные ничего не замечают.
 *
 * <p>⚠️ {@code status == 0} означает «не от HTTP»: нет токена, файл
 * не найден, корень кузницы не найден. Ноль выбран потому, что кода
 * ответа с таким номером не существует, и проверка на него не может
 * случайно совпасть с настоящим ответом сервера.
 */
public class CliException extends RuntimeException {

    private static final long serialVersionUID = 1L;

    /** Код ответа платформы или 0, если ошибка не от HTTP. */
    private final int status;

    public CliException(String message) {
        this(message, 0);
    }

    public CliException(String message, int status) {
        super(message);
        this.status = status;
    }

    public CliException(String message, Throwable cause) {
        super(message, cause);
        this.status = 0;
    }

    /** Код ответа платформы; 0 — ошибка возникла не из ответа. */
    public int status() {
        return status;
    }
}
